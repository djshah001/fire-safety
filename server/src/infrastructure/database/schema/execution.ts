export const projectMilestones = pgTable('project_milestones', {
  id: uuid('id').primaryKey().defaultRandom(),
  companyId: uuid('company_id').notNull().references(() => companies.id, { onDelete: 'restrict' }),
  projectId: uuid('project_id').notNull().references(() => projects.id, { onDelete: 'cascade' }),
  milestoneNumber: varchar('milestone_number', { length: 40 }).notNull(),
  name: varchar('name', { length: 200 }).notNull(),
  description: varchar('description', { length: 1_000 }),
  targetDate: date('target_date').notNull(),
  actualDate: date('actual_date'),
  status: varchar('status', { length: 30 }).notNull().default('pending'),
  billingPercentage: numeric('billing_percentage', { precision: 5, scale: 2 }).notNull().default('0.00'),
  orderIndex: integer('order_index').notNull().default(1),
  rowVersion: integer('row_version').notNull().default(1),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
}, (table) => [
  uniqueIndex('project_milestones_number_uidx').on(table.companyId, table.projectId, table.milestoneNumber),
  index('project_milestones_project_status_idx').on(table.companyId, table.projectId, table.status),
  check('project_milestones_status_valid', sql`${table.status} in ('pending', 'in_progress', 'completed', 'delayed')`),
  check('project_milestones_billing_pct_valid', sql`${table.billingPercentage} >= 0 and ${table.billingPercentage} <= 100`),
  check('project_milestones_row_version_positive', sql`${table.rowVersion} > 0`),
]);

export const projectTasks = pgTable('project_tasks', {
  id: uuid('id').primaryKey().defaultRandom(),
  companyId: uuid('company_id').notNull().references(() => companies.id, { onDelete: 'restrict' }),
  projectId: uuid('project_id').notNull().references(() => projects.id, { onDelete: 'cascade' }),
  milestoneId: uuid('milestone_id').references(() => projectMilestones.id, { onDelete: 'set null' }),
  taskNumber: varchar('task_number', { length: 40 }).notNull(),
  title: varchar('title', { length: 200 }).notNull(),
  description: varchar('description', { length: 1_000 }),
  assignedUserId: uuid('assigned_user_id').references(() => users.id, { onDelete: 'set null' }),
  plannedStartDate: date('planned_start_date').notNull(),
  plannedEndDate: date('planned_end_date').notNull(),
  actualStartDate: date('actual_start_date'),
  actualEndDate: date('actual_end_date'),
  status: varchar('status', { length: 30 }).notNull().default('not_started'),
  progressPercentage: integer('progress_percentage').notNull().default(0),
  weightage: numeric('weightage', { precision: 5, scale: 2 }).notNull().default('1.00'),
  plannedQuantity: numeric('planned_quantity', { precision: 14, scale: 4 }),
  actualQuantity: numeric('actual_quantity', { precision: 14, scale: 4 }).notNull().default('0.0000'),
  unitSymbol: varchar('unit_symbol', { length: 20 }),
  blockedReason: varchar('blocked_reason', { length: 500 }),
  rowVersion: integer('row_version').notNull().default(1),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
}, (table) => [
  uniqueIndex('project_tasks_number_uidx').on(table.companyId, table.projectId, table.taskNumber),
  index('project_tasks_assigned_status_idx').on(table.companyId, table.assignedUserId, table.status),
  index('project_tasks_milestone_idx').on(table.companyId, table.milestoneId),
  check('project_tasks_status_valid', sql`${table.status} in ('not_started', 'in_progress', 'completed', 'blocked')`),
  check('project_tasks_progress_pct_valid', sql`${table.progressPercentage} >= 0 and ${table.progressPercentage} <= 100`),
  check('project_tasks_weightage_positive', sql`${table.weightage} > 0`),
  check('project_tasks_dates_valid', sql`${table.plannedEndDate} >= ${table.plannedStartDate}`),
  check('project_tasks_row_version_positive', sql`${table.rowVersion} > 0`),
]);

